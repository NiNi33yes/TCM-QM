def load_master() -> pd.DataFrame:
    df = pd.read_csv(DATA / "tables" / "tcm_qm_master.csv", encoding="utf-8-sig", dtype={"cid": str})
    return df


def _num(series: pd.Series) -> np.ndarray:
    return pd.to_numeric(series, errors="coerce").dropna().to_numpy()


def parse_formula(formula: str) -> dict:
    """Hill-notation element count, e.g. 'C12H22O11' -> {'C':12,'H':22,'O':11}."""
    counts: dict = {}
    for el, n in re.findall(r"([A-Z][a-z]?)(\d*)", str(formula)):
        counts[el] = counts.get(el, 0) + (int(n) if n else 1)
    return counts


