BUILDERS = {"fig1": fig1, "fig2": fig2, "fig3": fig3, "fig4": fig4, "fig5": fig5, "fig7": fig7}


def main() -> None:
    which = sys.argv[1:] or list(BUILDERS)
    for name in which:
        if name not in BUILDERS:
            print(f"unknown figure '{name}' (choose from {', '.join(BUILDERS)})")
            continue
        BUILDERS[name]()


if __name__ == "__main__":
    main()
