# --------------------------------------------------------------------------- #
# Figure 2 -- chemical space
# --------------------------------------------------------------------------- #
def fig2() -> None:
    df = load_master()

    # (a) element occurrence counts (molecules containing each element)
    elem_counter: Counter = Counter()
    for f in df["molecular_formula"]:
        for el in parse_formula(f):
            elem_counter[el] += 1
    top = elem_counter.most_common(12)
    els = [e for e, _ in top]
    counts = [c for _, c in top]

    mass = _num(df["molecular_mass_amu"])
    xlogp = pd.to_numeric(df["pubchem_XLogP"], errors="coerce")
    tpsa = pd.to_numeric(df["pubchem_TPSA"], errors="coerce")
    comp = pd.to_numeric(df["pubchem_Complexity"], errors="coerce")
    heavy = _num(df["heavy_atom_count"])
    mask_xy = xlogp.notna() & tpsa.notna()

    fig, axes = plt.subplots(2, 2, figsize=(11, 8), dpi=200)

    axes[0, 0].bar(els, counts, color=TEAL, edgecolor="none")
    axes[0, 0].set_ylabel("Molecules containing element")
    axes[0, 0].set_title("(a) Element occurrence", fontweight="bold")

    axes[0, 1].hist(mass, bins=40, color=TEAL, edgecolor="white")
    axes[0, 1].set_xlabel("Molecular mass (amu)")
    axes[0, 1].set_ylabel("Molecule count")
    axes[0, 1].set_title("(b) Molecular-mass distribution", fontweight="bold")

    axes[1, 0].scatter(xlogp[mask_xy], tpsa[mask_xy], s=8, alpha=0.45, color=TEAL)
    axes[1, 0].set_xlabel("PubChem XLogP")
    axes[1, 0].set_ylabel("Topological polar surface area (Å²)")
    axes[1, 0].set_title("(c) XLogP vs TPSA", fontweight="bold")

    axes[1, 1].scatter(heavy, comp, s=8, alpha=0.45, color=GOLD)
    axes[1, 1].set_xlabel("Heavy-atom count")
    axes[1, 1].set_ylabel("PubChem complexity")
    axes[1, 1].set_title("(d) Heavy-atom count vs complexity", fontweight="bold")

    fig.tight_layout()
    fig.savefig(FIGDIR / "Fig2_chemical_space.png", dpi=200)
    plt.close(fig)
    print(f"Fig2: top elements={dict(top[:6])}, mass n={len(mass)}, xlogp/tpsa n={int(mask_xy.sum())}")


# --------------------------------------------------------------------------- #
# Figure 3 -- distributions of representative quantum-chemical properties
# --------------------------------------------------------------------------- #
def fig3() -> None:
    df = load_master()
    panels = [
        ("homo_lumo_gap_ev", "HOMO-LUMO gap (eV)"),
        ("dipole_magnitude_debye", "Dipole magnitude (Debye)"),
        ("zpe_eh", "Zero-point energy (Eh)"),
        ("final_entropy_term_eh", "Entropy term (Eh)"),
        ("lowest_positive_frequency_cm1", "Lowest positive frequency (cm⁻¹)"),
        ("highest_frequency_cm1", "Highest frequency (cm⁻¹)"),
    ]
    fig, axes = plt.subplots(2, 3, figsize=(13, 7.5), dpi=200)
    for ax, (col, label) in zip(axes.flat, panels):
        vals = _num(df[col])
        ax.hist(vals, bins=40, color=TEAL, edgecolor="white")
        ax.axvline(np.median(vals), color=GOLD, linestyle="--", lw=1.4)
        ax.set_xlabel(label)
        ax.set_ylabel("Count")
        ax.set_title(f"{label}\n(n={len(vals):,}, median={np.median(vals):.4g})", fontsize=11, fontweight="bold")
    fig.tight_layout()
    fig.savefig(FIGDIR / "Fig3_quantum_property_atlas.png", dpi=200)
    plt.close(fig)
    med = {col: f"{np.median(_num(df[col])):.4g}" for col, _ in panels}
    print(f"Fig3: medians={med}")


# --------------------------------------------------------------------------- #
# Figure 4 -- technical validation, geometry provenance, exceptions
# --------------------------------------------------------------------------- #
def fig4() -> None:
    df = load_master()
    geo = pd.read_csv(DATA / "audits" / "initial_geometry_pubchem3d_full_results_frozen.csv",
                      encoding="utf-8-sig", dtype={"cid": str})

    n_all = len(df)
    n_term = int(df["normal_termination"].astype(int).sum())
    n_conv = int(df["optimization_converged"].astype(int).sum())
    n_freq = int((df["frequency_count"].astype(int) > 0).sum())
    n_zero_imag = int((df["imaginary_frequency_count"].astype(int) == 0).sum())

    geo_comparable = geo[geo["comparison_status"] == "direct_atom_order"]
    rmsd = pd.to_numeric(geo_comparable["heavy_atom_rmsd_angstrom"], errors="coerce")
    graph_row = geo[geo["cid"] == "10946210"]
    graph_rmsd = float(graph_row["graph_mapping_rmsd_angstrom"].iloc[0]) if len(graph_row) else None

    imag = df[df["imaginary_frequency_count"].astype(int) == 1]
    imag = imag.sort_values("lowest_frequency_cm1")

    fig = plt.figure(figsize=(13, 9), dpi=200)
    gs = fig.add_gridspec(3, 3, hspace=0.55, wspace=0.35)

    ax_a = fig.add_subplot(gs[0, 0])
    checks = ["Normal\ntermination", "Optimization\nconverged", "Frequency\nanalysis", "Zero imaginary\nfrequency"]
    vals = [n_term, n_conv, n_freq, n_zero_imag]
    ax_a.bar(range(4), vals, color=TEAL)
    ax_a.set_xticks(range(4))
    ax_a.set_xticklabels(checks, fontsize=8.5)
    ax_a.set_ylim(0, n_all * 1.12)
    for i, v in enumerate(vals):
        ax_a.text(i, v, f"{v:,}", ha="center", va="bottom", fontsize=9)
    ax_a.set_title("(a) Record-level checks", fontsize=11, fontweight="bold")

    ax_b = fig.add_subplot(gs[0, 1])
    ax_b.barh([2, 1, 0], [len(geo), len(geo_comparable), len(graph_row)],
              color=[TEAL, TEAL, GOLD])
    ax_b.set_yticks([2, 1, 0])
    ax_b.set_yticklabels(["PubChem3D\nretrieved", "Direct atom-order\ncomparable", "Graph-mapped\nrepair"], fontsize=8.5)
    ax_b.set_xlabel("Records")
    ax_b.set_title("(b) Starting-geometry provenance", fontsize=11, fontweight="bold")

    ax_c = fig.add_subplot(gs[0, 2])
    ax_c.hist(rmsd, bins=40, color=TEAL, edgecolor="white")
    if graph_rmsd is not None:
        ax_c.axvline(graph_rmsd, color=GOLD, linestyle="--", lw=1.6)
        ax_c.text(graph_rmsd, ax_c.get_ylim()[1] * 0.9, f"  10946210\n  {graph_rmsd:.3f} Å",
                  color="#8a6d1a", fontsize=8)
    ax_c.set_xlabel("Heavy-atom RMSD (Å)")
    ax_c.set_ylabel("Records")
    ax_c.set_title("(c) RMSD distribution (direct order)", fontsize=11, fontweight="bold")

    ax_d = fig.add_subplot(gs[1, :])
    cids = list(imag["cid"])
    freqs = [float(x) for x in imag["lowest_frequency_cm1"]]
    colors = [GOLD if v < -3.5 else TEAL for v in freqs]
    ax_d.bar(range(len(cids)), freqs, color=colors)
    ax_d.axhline(0, color=INK, lw=1)
    ax_d.set_xticks(range(len(cids)))
    ax_d.set_xticklabels(cids, fontsize=9)
    ax_d.set_ylabel("Signed lowest frequency (cm⁻¹)")
    ax_d.set_title("(d) Five retained minor-negative-mode records", fontsize=11, fontweight="bold")
    for i, v in enumerate(freqs):
        ax_d.text(i, v, f"{v:.2f}", ha="center", va="top" if v < 0 else "bottom", fontsize=8.5)

    ax_e = fig.add_subplot(gs[2, :])
    ax_e.barh([1, 0], [2, 1], color=[TEAL, GOLD])
    ax_e.set_yticks([1, 0])
    ax_e.set_yticklabels(["Formal-charge repair\n(CIDs 248, 5571)", "E/Z stereochemical repair\n(CID 10946210)"], fontsize=9)
    ax_e.set_xlabel("Records")
    ax_e.set_title("(e) Identity and stereochemical repairs", fontsize=11, fontweight="bold")

    fig.savefig(FIGDIR / "Fig4_quality_control.png", dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"Fig4: term={n_term} conv={n_conv} freq={n_freq} zero_imag={n_zero_imag}; "
          f"geo comparable={len(geo_comparable)} graph_rmsd={graph_rmsd}; imag={list(zip(cids, freqs))}")


# --------------------------------------------------------------------------- #
# Figure 5 -- ORCA software-version provenance
# --------------------------------------------------------------------------- #
def fig5() -> None:
    df = load_master()
    cnt = df["orca_version"].value_counts()
    v601 = int(cnt.get("6.0.1", 0))
    v611 = int(cnt.get("6.1.1", 0))

    gap = pd.to_numeric(df["homo_lumo_gap_ev"], errors="coerce")
    dip = pd.to_numeric(df["dipole_magnitude_debye"], errors="coerce")
    gap601 = gap[df["orca_version"] == "6.0.1"].to_numpy()
    gap611 = gap[df["orca_version"] == "6.1.1"].to_numpy()
    dip601 = dip[df["orca_version"] == "6.0.1"].to_numpy()
    dip611 = dip[df["orca_version"] == "6.1.1"].to_numpy()

    fig, axes = plt.subplots(1, 3, figsize=(13, 4.2), dpi=200)

    axes[0].bar(["6.0.1", "6.1.1"], [v601, v611], color=[TEAL, GOLD])
    for i, v in enumerate([v601, v611]):
        axes[0].text(i, v, f"{v:,}", ha="center", va="bottom", fontsize=10)
    axes[0].set_ylabel("Records")
    axes[0].set_title("(a) Release counts by version", fontsize=11, fontweight="bold")

    axes[1].hist(gap601, bins=35, alpha=0.6, color=TEAL, label="6.0.1")
    axes[1].hist(gap611, bins=35, alpha=0.6, color=GOLD, label="6.1.1")
    axes[1].set_xlabel("HOMO-LUMO gap (eV)")
    axes[1].set_ylabel("Records")
    axes[1].legend(fontsize=9)
    axes[1].set_title("(b) Orbital-gap distribution", fontsize=11, fontweight="bold")

    axes[2].hist(dip601, bins=35, alpha=0.6, color=TEAL, label="6.0.1")
    axes[2].hist(dip611, bins=35, alpha=0.6, color=GOLD, label="6.1.1")
    axes[2].set_xlabel("Dipole magnitude (Debye)")
    axes[2].set_ylabel("Records")
    axes[2].legend(fontsize=9)
    axes[2].set_title("(c) Dipole-magnitude distribution", fontsize=11, fontweight="bold")

    fig.tight_layout()
    fig.savefig(FIGDIR / "Fig5_software_provenance.png", dpi=200)
    plt.close(fig)
    print(f"Fig5: 6.0.1={v601} 6.1.1={v611}  (sum={v601 + v611})")


