"""Reproduce TCM-QM manuscript Figures 1-5 from the frozen v5 release.

Every figure reads only from the frozen release under 02_数据冻结最新版_v5
(tables/ + audits/) and writes a PNG into 01_论文最新版_v6/figures_repro/. No
value is recomputed from scratch; all numbers are derived from the deposited
CSVs so a reviewer can regenerate each panel in a clean environment and check it
against the manuscript's Technical Validation section.

Figure 6 is generated by build_fig6_ml_readiness.py (Extra Trees mean +/- SD,
four targets); Figure 7 is a record-centred architecture schematic whose source
must be archived separately (it is not data-derived).

Usage:
    python build_figures.py            # rebuild all of Fig 1-5
    python build_figures.py fig2 fig3  # rebuild a subset
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

import matplotlib

