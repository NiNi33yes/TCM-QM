# are not pixel-identical to the authored figures.
FIGDIR = ROOT / "01_论文最新版_v6" / "figures_repro"
FIGDIR.mkdir(parents=True, exist_ok=True)

# Shared colour palette (teal primary + gold accent, consistent with Fig. 6).
TEAL = "#207070"
GOLD = "#D0A040"
GREY = "#8A8A8A"
